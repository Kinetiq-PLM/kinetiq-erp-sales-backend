class CampaignsAdmin(admin.ModelAdmin):
    def save_model(self, request, obj, form, change):
        """Set a flag before saving so that the model knows it's from the admin panel."""
        obj._from_admin = True  # Mark as coming from the admin panel
        obj.save()  # Calls the model's save method


class Campaigns(models.Model):
    class Type(models.TextChoices):
        EMAIL = "Email"
        SMS = "SMS"
        REFERRAL = "Referral"

    campaign_id = models.CharField(primary_key=True, max_length=255, blank=True)
    campaign_name = models.CharField(max_length=255)
    type = models.TextField(choices=Type, default=Type.EMAIL)
    start_date = models.DateTimeField(default=timezone.now())
    end_date = models.DateTimeField(default=timezone.now())

    class Meta:
        managed = False
        db_table = '"sales"."campaigns"'

    def save(self, *args, **kwargs):
        if hasattr(self, "_from_admin") and self._from_admin:
            # If coming from admin, use the default Django ORM save
            super().save(*args, **kwargs)
        elif self.campaign_id:
            # needed because postgres autogenerates id and django
            # cant return the autogenerated id
            self.update()
        else:
            self.insert()

    def insert(self):
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO sales.campaigns (campaign_name, type, start_date, end_date)
                VALUES (%s, %s, %s, %s)
                RETURNING campaign_id;
            """,
                [
                    self.campaign_name,
                    self.type,
                    self.start_date,
                    self.end_date,
                ],
            )
            row = cursor.fetchone()
            if row:
                self.campaign_id = row[
                    0
                ]  # Update the instance with the new statement_id

    def update(self):
        with connection.cursor() as cursor:
            cursor.execute(
                """
                UPDATE sales.campaigns 
                SET campaign_name = %s, type = %s, start_date = %s, end_date = %s
                WHERE campaign_id = %s;
            """,
                [
                    self.campaign_name,
                    self.type,
                    self.start_date,
                    self.end_date,
                    self.campaign_id,
                ],
            )


