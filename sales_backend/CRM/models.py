class Ticket(models.Model):
    class Status(models.TextChoices):
        OPEN = "Open"
        IN_PROGRESS = "In Progress"
        CLOSED = "Closed"

    class Priority(models.TextChoices):
        LOW = "Low"
        MEDIUM = "Medium"
        HIGH = "High"
        URGENT = "Urgent"

    class Type(models.TextChoices):
        SALES = "Sales"
        SERVICE = "Service"

    ticket_id = models.CharField(primary_key=True, max_length=255, blank=True)
    customer = models.ForeignKey(to="customer.Customer", on_delete=models.CASCADE)
    salesrep = models.ForeignKey(to=Employees, on_delete=models.CASCADE, null=True)
    subject = models.CharField(max_length=255)
    description = models.TextField()
    type = models.TextField(choices=Type)
    status = models.TextField(choices=Status)
    priority = models.TextField(choices=Priority)
    created_at = models.DateTimeField(default=timezone.now())

    class Meta:
        managed = False
        db_table = '"sales"."ticket"'

    def save(self, *args, **kwargs):
        if hasattr(self, "_from_admin") and self._from_admin:
            # If coming from admin, use the default Django ORM save
            super().save(*args, **kwargs)
        elif self.ticket_id:
            # needed because postgres autogenerates id and django
            # cant return the autogenerated id
            self.update()
        else:
            self.insert()

    def insert(self):
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO sales.ticket (customer_id, salesrep_id, subject, description, status, priority, created_at, type)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING ticket_id;
            """,
                [
                    self.customer.customer_id,
                    self.salesrep.employee_id,
                    self.subject,
                    self.description,
                    self.status,
                    self.priority,
                    self.created_at,
                    self.type,
                ],
            )
            row = cursor.fetchone()
            if row:
                self.ticket_id = row[0]  # Update the instance with the new statement_id

    def update(self):
        with connection.cursor() as cursor:
            cursor.execute(
                """
                UPDATE sales.ticket 
                SET customer_id = %s, salesrep_id = %s, subject = %s, description = %s, status = %s, priority = %s, created_at = %s, type = %s
                WHERE ticket_id = %s;
            """,
                [
                    self.customer.customer_id,
                    self.salesrep.employee_id,
                    self.subject,
                    self.description,
                    self.status,
                    self.priority,
                    self.created_at,
                    self.type,
                    self.ticket_id,
                ],
            )


